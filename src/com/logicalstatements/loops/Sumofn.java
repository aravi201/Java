package com.logicalstatements.loops;

public class Sumofn {

	public static void main(String[] args) {
		int i=1;
		int n=100;
		int sum=0;
		for(i=1;i<=n;i++) {
			sum=sum+i;
			
		}
		System.out.println("the sum of the natural numbers is:"+sum);
		

	}

}
